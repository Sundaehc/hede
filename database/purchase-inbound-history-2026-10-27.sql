CREATE TABLE IF NOT EXISTS public.jst_purchase_inbound_history_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_checksum text NOT NULL UNIQUE,
    source_file text NOT NULL,
    source_bytes bigint NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    imported_rows bigint NOT NULL DEFAULT 0,
    first_inbound_date date,
    last_inbound_date date,
    started_at timestamptz,
    completed_at timestamptz,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.jst_purchase_inbound_history (
    inbound_date date NOT NULL,
    source_id bigint NOT NULL REFERENCES public.jst_purchase_inbound_history_sources(id),
    source_sheet text NOT NULL,
    source_row_number integer NOT NULL,
    inbound_id text NOT NULL,
    purchase_order_id text,
    inbound_at timestamp NOT NULL,
    created_at_source timestamp,
    status text NOT NULL,
    inbound_type text,
    warehouse_operator text,
    warehouse text NOT NULL DEFAULT '',
    virtual_warehouse text,
    supplier text,
    supplier_code text,
    style_color_code text NOT NULL DEFAULT '',
    goods_code text NOT NULL,
    original_sku text NOT NULL DEFAULT '',
    goods_name text,
    color_spec text,
    size text,
    quantity numeric NOT NULL,
    unit_price numeric,
    amount numeric,
    returned_quantity numeric,
    quality_good_quantity numeric,
    quality_defect_quantity numeric,
    receipt_class text NOT NULL
        CHECK (receipt_class IN ('purchase_candidate', 'customer_return_candidate', 'rework_candidate', 'other')),
    detail_remark text,
    remark text,
    raw_payload jsonb NOT NULL,
    acquired_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (inbound_date, source_id, source_sheet, source_row_number),
    CHECK (inbound_date = inbound_at::date)
) PARTITION BY RANGE (inbound_date);

CREATE INDEX IF NOT EXISTS ix_jst_inbound_history_goods_date
    ON public.jst_purchase_inbound_history (goods_code, inbound_date DESC);
CREATE INDEX IF NOT EXISTS ix_jst_inbound_history_style_date
    ON public.jst_purchase_inbound_history (style_color_code, inbound_date DESC);
CREATE INDEX IF NOT EXISTS ix_jst_inbound_history_original_date
    ON public.jst_purchase_inbound_history (original_sku, inbound_date DESC)
    WHERE original_sku <> '';
CREATE INDEX IF NOT EXISTS ix_jst_inbound_history_warehouse_date
    ON public.jst_purchase_inbound_history (warehouse, inbound_date DESC);
CREATE INDEX IF NOT EXISTS ix_jst_inbound_history_order_date
    ON public.jst_purchase_inbound_history (purchase_order_id, inbound_date DESC)
    WHERE purchase_order_id IS NOT NULL;

CREATE OR REPLACE VIEW public.v_jst_purchase_inbound_age_candidates AS
SELECT history.*
FROM public.jst_purchase_inbound_history AS history
JOIN public.jst_purchase_inbound_history_sources AS source ON source.id = history.source_id
WHERE source.status = 'completed'
    AND history.status = '已入库'
    AND history.inbound_type = '采购进仓'
    AND history.quantity > 0
    AND history.receipt_class = 'purchase_candidate';

CREATE MATERIALIZED VIEW IF NOT EXISTS public.mv_jst_purchase_inbound_age_reference AS
SELECT goods_code, style_color_code, original_sku, warehouse,
    min(inbound_date) AS first_inbound_date,
    max(inbound_date) AS last_inbound_date,
    sum(quantity) AS received_quantity,
    count(*) AS receipt_line_count
FROM public.v_jst_purchase_inbound_age_candidates
GROUP BY goods_code, style_color_code, original_sku, warehouse
WITH NO DATA;

CREATE UNIQUE INDEX IF NOT EXISTS ux_jst_inbound_age_reference_key
    ON public.mv_jst_purchase_inbound_age_reference (goods_code, style_color_code, original_sku, warehouse);
CREATE INDEX IF NOT EXISTS ix_jst_inbound_age_reference_style
    ON public.mv_jst_purchase_inbound_age_reference (style_color_code, first_inbound_date);
CREATE INDEX IF NOT EXISTS ix_jst_inbound_age_reference_original
    ON public.mv_jst_purchase_inbound_age_reference (original_sku, first_inbound_date);

COMMENT ON TABLE public.jst_purchase_inbound_history IS
    '采购入库来源明细，按入库日期年度分区；来源文件校验和及行位置幂等，不等同于出入库消耗台账';
COMMENT ON COLUMN public.jst_purchase_inbound_history.receipt_class IS
    '依据供应商和备注标记采购、客退、返修候选；不是已确认业务分类';
COMMENT ON MATERIALIZED VIEW public.mv_jst_purchase_inbound_age_reference IS
    '已完成导入的正向采购候选入库日期参考；历史采购数量不是当前库存，首入日期不是剩余实物的准确库龄';
